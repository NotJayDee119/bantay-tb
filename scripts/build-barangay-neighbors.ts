/**
 * Build the queen-contiguity spatial weights for Getis-Ord Gi* and Moran's I.
 *
 * Two barangays are queen neighbours when their boundaries share an edge OR a
 * single corner. The source polygons (public/data/davao-city-barangays.geojson)
 * are cut from one boundary dataset, so adjoining barangays share vertices;
 * a vertex lying within TOLERANCE_M of the other polygon's boundary also counts,
 * which catches a border where simplification dropped one side's vertex.
 *
 * A barangay with no contiguous neighbour falls back to its K_FALLBACK nearest
 * barangays by centroid (added in both directions so W stays symmetric).
 *
 * Writes:
 *   src/data/barangayNeighbors.json                          — client + tests
 *   supabase/migrations/20261023000001_barangay_neighbors_seed.sql — DB table
 *
 * Run: npx tsx scripts/build-barangay-neighbors.ts
 */
import { readFileSync, writeFileSync } from "node:fs";

const TOLERANCE_M = 15;
const K_FALLBACK = 2;

type Ring = [number, number][];
interface Feature {
  properties: { psgc: number };
  geometry:
    | { type: "Polygon"; coordinates: Ring[] }
    | { type: "MultiPolygon"; coordinates: Ring[][] };
}

const geo = JSON.parse(
  readFileSync("public/data/davao-city-barangays.geojson", "utf8")
) as { features: Feature[] };

interface Shape {
  psgc: number;
  rings: Ring[];
  bbox: [number, number, number, number];
  cx: number;
  cy: number;
}

const shapes: Shape[] = geo.features.map((f) => {
  const rings =
    f.geometry.type === "Polygon"
      ? f.geometry.coordinates
      : f.geometry.coordinates.flat();
  let minX = Infinity,
    minY = Infinity,
    maxX = -Infinity,
    maxY = -Infinity,
    sx = 0,
    sy = 0,
    n = 0;
  for (const r of rings)
    for (const [x, y] of r) {
      minX = Math.min(minX, x);
      minY = Math.min(minY, y);
      maxX = Math.max(maxX, x);
      maxY = Math.max(maxY, y);
      sx += x;
      sy += y;
      n += 1;
    }
  return {
    psgc: f.properties.psgc,
    rings,
    bbox: [minX, minY, maxX, maxY],
    cx: sx / n,
    cy: sy / n,
  };
});

// Local equirectangular metres — accurate to well under a metre at 7°N over
// the few-km spans compared here.
const M_PER_DEG_LAT = 110_574;
const M_PER_DEG_LON = 111_320 * Math.cos((7.1 * Math.PI) / 180);

function pointSegM(
  p: [number, number],
  a: [number, number],
  b: [number, number]
): number {
  const px = p[0] * M_PER_DEG_LON,
    py = p[1] * M_PER_DEG_LAT;
  const ax = a[0] * M_PER_DEG_LON,
    ay = a[1] * M_PER_DEG_LAT;
  const bx = b[0] * M_PER_DEG_LON,
    by = b[1] * M_PER_DEG_LAT;
  const dx = bx - ax,
    dy = by - ay;
  const len2 = dx * dx + dy * dy;
  const t = len2 === 0 ? 0 : Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len2));
  return Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
}

function nearBoundary(p: [number, number], s: Shape): boolean {
  for (const r of s.rings)
    for (let i = 0; i + 1 < r.length; i++)
      if (pointSegM(p, r[i], r[i + 1]) <= TOLERANCE_M) return true;
  return false;
}

function touches(a: Shape, b: Shape): boolean {
  const padX = TOLERANCE_M / M_PER_DEG_LON,
    padY = TOLERANCE_M / M_PER_DEG_LAT;
  if (
    a.bbox[0] > b.bbox[2] + padX ||
    b.bbox[0] > a.bbox[2] + padX ||
    a.bbox[1] > b.bbox[3] + padY ||
    b.bbox[1] > a.bbox[3] + padY
  )
    return false;
  for (const r of a.rings) for (const p of r) if (nearBoundary(p, b)) return true;
  for (const r of b.rings) for (const p of r) if (nearBoundary(p, a)) return true;
  return false;
}

const adj = new Map<number, Map<number, "queen" | "knn">>(
  shapes.map((s) => [s.psgc, new Map()])
);
for (let i = 0; i < shapes.length; i++)
  for (let j = i + 1; j < shapes.length; j++)
    if (touches(shapes[i], shapes[j])) {
      adj.get(shapes[i].psgc)!.set(shapes[j].psgc, "queen");
      adj.get(shapes[j].psgc)!.set(shapes[i].psgc, "queen");
    }

let islands = 0;
for (const s of shapes) {
  if (adj.get(s.psgc)!.size > 0) continue;
  islands += 1;
  const nearest = shapes
    .filter((o) => o.psgc !== s.psgc)
    .map((o) => ({
      psgc: o.psgc,
      d: Math.hypot((o.cx - s.cx) * M_PER_DEG_LON, (o.cy - s.cy) * M_PER_DEG_LAT),
    }))
    .sort((x, y) => x.d - y.d)
    .slice(0, K_FALLBACK);
  for (const n of nearest) {
    adj.get(s.psgc)!.set(n.psgc, "knn");
    if (!adj.get(n.psgc)!.has(s.psgc)) adj.get(n.psgc)!.set(s.psgc, "knn");
  }
}

const out: Record<string, number[]> = {};
const rows: string[] = [];
for (const s of [...shapes].sort((a, b) => a.psgc - b.psgc)) {
  const ns = [...adj.get(s.psgc)!.entries()].sort((a, b) => a[0] - b[0]);
  out[s.psgc] = ns.map(([p]) => p);
  for (const [p, kind] of ns) rows.push(`  (${s.psgc}, ${p}, '${kind}')`);
}

writeFileSync("src/data/barangayNeighbors.json", JSON.stringify(out, null, 0) + "\n");

const sql = `-- GENERATED by scripts/build-barangay-neighbors.ts — do not edit by hand.
-- Queen-contiguity spatial weights for Davao City's ${shapes.length} barangays:
-- ${rows.length / 2} neighbour pairs (stored in both directions), ${islands} barangay(s)
-- on the k-nearest fallback.

truncate public.barangay_neighbors;

insert into public.barangay_neighbors (barangay_psgc, neighbor_psgc, kind) values
${rows.join(",\n")}
on conflict do nothing;
`;
writeFileSync("supabase/migrations/20261023000001_barangay_neighbors_seed.sql", sql);

const degrees = shapes.map((s) => adj.get(s.psgc)!.size);
console.log(
  `${shapes.length} barangays · ${rows.length / 2} pairs · islands ${islands} · ` +
    `degree min ${Math.min(...degrees)} max ${Math.max(...degrees)} mean ${(
      degrees.reduce((a, b) => a + b, 0) / degrees.length
    ).toFixed(2)}`
);
